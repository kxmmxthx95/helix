#!/usr/bin/env python3
"""Ports the two generic Postgres triggers to D1 and lists the rest.

    python3 scripts/pg-triggers-to-d1.py     # -> worker/d1/triggers.sql + worker/d1/triggers.json   (read-only against Postgres)

 * log_audit (59 tables, AFTER INSERT/UPDATE/DELETE): SQLite AFTER triggers that write audit_logs exactly like the Postgres function,
   including "skip when the actor has no role or only student/parent". SQLite has no auth.uid(), so the API runs
   `UPDATE _ctx SET uid = ?, sid = ?` first in every write batch (a batch is one transaction and D1 runs one writer at a time).
   JSON is shaped like to_jsonb(): booleans true/false, money back in baht, JSON columns nested. Load this file AFTER importing data.
 * touch_updated_at (BEFORE UPDATE, sets updated_at = now()): done by the API, which adds `updated_at = now` to the SET list of tables in
   triggers.json "touch" (SQLite cannot change NEW in a BEFORE trigger).
 * everything else (validation `check_*`, sync_*, seed_* … ~100 small functions) is listed under "manual" for hand porting.
"""
import json, subprocess, sys
from pathlib import Path

D1 = Path(__file__).resolve().parent.parent / "worker" / "d1"
manifest = json.loads((D1 / "columns.json").read_text())


def q(sql):
    p = subprocess.run(["supabase", "db", "query", "--linked", sql], capture_output=True, text=True, stdin=subprocess.DEVNULL)
    t = p.stdout + p.stderr
    try:
        return json.loads(t[t.index("{"): t.rindex("}") + 1])["rows"]
    except Exception:
        sys.exit(f"query failed:\n{t[:600]}")


trg = q("""select c.relname t, tg.tgname n, p.proname fn, (tg.tgtype & 2)>0 before_, (tg.tgtype & 4)>0 ins, (tg.tgtype & 8)>0 del, (tg.tgtype & 16)>0 upd
  from pg_trigger tg join pg_class c on c.oid=tg.tgrelid join pg_proc p on p.oid=tg.tgfoid
  where c.relnamespace='public'::regnamespace and not tg.tgisinternal order by 1,2""")
pk = {r["t"]: r["cols"].split(",") for r in q("""select c.relname t, string_agg(a.attname, ',' order by array_position(i.indkey::int2[], a.attnum)) cols
  from pg_index i join pg_class c on c.oid=i.indrelid join pg_attribute a on a.attrelid=c.oid and a.attnum=any(i.indkey)
  where i.indisprimary and c.relnamespace='public'::regnamespace group by 1""")}

audit = {t["t"]: t for t in trg if t["fn"] == "log_audit"}
touch = sorted({t["t"] for t in trg if t["fn"] == "touch_updated_at"})
manual = [{"table": t["t"], "trigger": t["n"], "function": t["fn"], "before": t["before_"], "events": [e for e, f in (("insert", t["ins"]), ("update", t["upd"]), ("delete", t["del"])) if f]}
          for t in trg if t["fn"] not in ("log_audit", "touch_updated_at")]


def jval(table, col, kind, row):
    ref = f"{row}.{col}"
    if kind == "bool":
        return f"CASE WHEN {ref} IS NULL THEN NULL WHEN {ref} THEN json('true') ELSE json('false') END"
    if kind == "json":
        return f"CASE WHEN {ref} IS NULL THEN NULL ELSE json({ref}) END"
    if kind == "money":
        return f"({ref} / 100.0)"
    return ref


def obj(table, row):
    return "json_object(" + ", ".join(f"'{c['col']}', {jval(table, c['col'], c['kind'], row)}" for c in manifest[table]) + ")"


WHO = "(SELECT uid FROM _ctx)"
ACTOR = f"{WHO} IS NOT NULL AND EXISTS (SELECT 1 FROM profile_roles WHERE profile_id = {WHO} AND role NOT IN ('student', 'parent'))"
out = ["-- GENERATED by scripts/pg-triggers-to-d1.py. Load AFTER the data import (the triggers would audit every imported row).",
       "CREATE TABLE IF NOT EXISTS _ctx (uid TEXT, sid TEXT);",
       "INSERT INTO _ctx SELECT NULL, NULL WHERE NOT EXISTS (SELECT 1 FROM _ctx);"]
for t in sorted(audit):
    if t not in manifest:
        continue
    cols = pk.get(t) or ["id"]
    rec = lambda r: " || ':' || ".join(f"COALESCE(CAST({r}.{c} AS TEXT), '')" for c in cols)
    for ev, flag in (("INSERT", audit[t]["ins"]), ("UPDATE", audit[t]["upd"]), ("DELETE", audit[t]["del"])):
        if not flag:
            continue
        row = "OLD" if ev == "DELETE" else "NEW"
        changes = {"INSERT": f"json_object('new', {obj(t, 'NEW')})", "DELETE": f"json_object('old', {obj(t, 'OLD')})",
                   "UPDATE": f"json_object('old', {obj(t, 'OLD')}, 'new', {obj(t, 'NEW')})"}[ev]
        out.append(f"CREATE TRIGGER audit_{t}_{ev.lower()} AFTER {ev} ON {t} FOR EACH ROW WHEN {ACTOR} BEGIN "
                   f"INSERT INTO audit_logs (actor_id, actor_roles, action, table_name, record_id, changes) VALUES ("
                   f"{WHO}, (SELECT json_group_array(role) FROM profile_roles WHERE profile_id = {WHO}), '{ev}', '{t}', {rec(row)}, {changes}); END;")

(D1 / "triggers.sql").write_text("\n".join(out) + "\n")
(D1 / "triggers.json").write_text(json.dumps({"touch": [t for t in touch if t in manifest], "audit": sorted(t for t in audit if t in manifest), "manual": manual}, indent=1) + "\n")
print(f"audit triggers on {len(audit)} tables, touch_updated_at on {len(touch)} tables, {len(manual)} triggers left to port by hand")
